-- 1. Tabla de Configuración de Producción
CREATE TABLE IF NOT EXISTS public.production_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    max_orders_per_day INT NOT NULL DEFAULT 8,
    delivery_days VARCHAR(50) NOT NULL DEFAULT '1,2,3,4,5,6',
    delivery_hours VARCHAR(50) NOT NULL DEFAULT '17:00 a 20:00 hs',
    whatsapp_number VARCHAR(30) NOT NULL DEFAULT '5493804232210'
);

-- 2. Tabla de Ingredientes (Insumos Base)
CREATE TABLE IF NOT EXISTS public.ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    unit_of_measure VARCHAR(20) NOT NULL CHECK (unit_of_measure IN ('gr', 'kg', 'ml', 'l', 'unidad')),
    cost_per_unit NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    stock_quantity NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabla de Productos
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(20) NOT NULL CHECK (category IN ('daily', 'event')),
    description TEXT,
    profit_margin_percentage NUMERIC(5,2) NOT NULL DEFAULT 35.00,
    fixed_overhead_percentage NUMERIC(5,2) NOT NULL DEFAULT 15.00,
    cost_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    final_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    is_active_in_catalog BOOLEAN NOT NULL DEFAULT TRUE,
    image_url VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Tabla de Recetas / Escandallos (Relación Producto - Ingrediente)
CREATE TABLE IF NOT EXISTS public.product_recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES public.ingredients(id) ON DELETE RESTRICT,
    quantity_required NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT uk_product_ingredient UNIQUE (product_id, ingredient_id)
);

-- 5. Tabla de Pedidos
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name VARCHAR(150) NOT NULL,
    client_phone VARCHAR(50) NOT NULL,
    delivery_date DATE NOT NULL,
    delivery_time_slot VARCHAR(50) NOT NULL DEFAULT '17:00 a 20:00 hs',
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'delivered', 'cancelled')),
    total_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Tabla de Items de Pedidos
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
    quantity INT NOT NULL DEFAULT 1,
    unit_price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    subtotal NUMERIC(10,2) NOT NULL DEFAULT 0.00
);

-- Índices de búsqueda
CREATE INDEX IF NOT EXISTS idx_orders_delivery_date ON public.orders(delivery_date);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_products_active ON public.products(is_active_in_catalog);

-- Habilitar RLS (Row Level Security)
ALTER TABLE public.production_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ingredients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_recipes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

